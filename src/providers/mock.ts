/** Rough, clearly synthetic token estimate (~4 characters per token). */
function syntheticUsage(input: string, output: string): Usage {
  return {
    inputTokens: Math.ceil(input.length / 4),
    outputTokens: Math.ceil(output.length / 4),
    synthetic: true,
  };
}

function abortError(message: string): Error {
  const err = new Error(message);
  err.name = 'AbortError';
  return err;
}

function delay(ms: number, message: string, signal?: AbortSignal): Promise<void> {
  if (signal?.aborted) return Promise.reject(abortError(message));
  if (ms <= 0) return Promise.resolve();
  return new Promise((resolve, reject) => {
    const onAbort = () => {
      clearTimeout(timer);
      reject(abortError(message));
    };
    const timer = setTimeout(() => {
      signal?.removeEventListener('abort', onAbort);
      resolve();
    }, ms);
    signal?.addEventListener('abort', onAbort, { once: true });
  });
}

export function slug(text: string, fallback = 'tarefa'): string {
  const s = text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    .replace(/-+$/g, '');
  return s || fallback;
}

export function splitIntoTasks(request: string, locale: Locale = 'pt-BR'): PlanTask[] {
  const parts = request
    .split(/\n|(?<=[.;!?])\s+/)
    .map((p) => p.replace(/^[-*\d.)\s]+/, '').trim())
    .filter((p) => p.length > 0)
    .slice(0, MAX_TASKS);
  return parts.map((title, i) => ({
    id: `task-${i + 1}`,
    title: title.length > 80 ? `${title.slice(0, 80)}…` : title,
    detail: TEXT[locale].taskDetail(i + 1),
  }));
}

const MAX_PICK = 3;
const FALLBACK_FILES = ['README.md', 'readme.md', 'package.json', 'Cargo.toml', 'pyproject.toml'];

function words(text: string): string[] {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((w) => w.length >= 4);
}

/** Picks up to three files whose path mentions words from the request. */
export function pickFiles(request: string, tree: string[]): string[] {
  const wanted = words(request);
  const scored = tree
    .map((path) => {
      const haystack = path.toLowerCase();
      const score = wanted.filter((w) => haystack.includes(w)).length;
      return { path, score };
    })
    .filter((f) => f.score > 0)
    .sort((a, b) => b.score - a.score || a.path.length - b.path.length)
    .map((f) => f.path);
  const fallback = FALLBACK_FILES.filter((f) => tree.includes(f));
  return [...new Set([...scored, ...fallback])].slice(0, MAX_PICK);
}

function commentFor(path: string, text: string): string | null {
  const ext = path.toLowerCase().split('.').pop() ?? '';
  if (['md', 'markdown', 'html', 'xml', 'svg', 'vue'].includes(ext)) return `<!-- ${text} -->`;
  if (['css', 'scss', 'less'].includes(ext)) return `/* ${text} */`;
  if (
    ['py', 'yml', 'yaml', 'toml', 'sh', 'rb', 'r', 'ps1', 'dockerfile', 'ini', 'cfg'].includes(ext)
  ) {
    return `# ${text}`;
  }
  if (
    [
      'ts',
      'tsx',
      'js',
      'jsx',
      'mjs',
      'cjs',
      'rs',
      'go',
      'java',
      'kt',
      'c',
      'h',
      'cpp',
      'cs',
      'swift',
      'php',
      'dart',
    ].includes(ext)
  ) {
    return `// ${text}`;
  }
  return null; // e.g. JSON has no comments: leave it alone
}

/** Canned, clearly-labelled reply used by the offline mock. */
export function mockReply(
  agent: AgentProfile,
  lastUserMessage: string,
  locale: Locale = 'pt-BR',
): string {
  const quote = lastUserMessage.trim().slice(0, 120);
  return [TEXT[locale].replies[agent.id], '', TEXT[locale].demoNote(quote)].join('\n');
}

function modifyFor(file: FileContent, task: PlanTask, locale: Locale): ProposedChange | null {
  const note = commentFor(file.path, TEXT[locale].fileNote(task.title));
  if (!note) return null;
  const first = file.content.split('\n')[0] ?? '';
  const diff = [
    `--- a/${file.path}`,
    `+++ b/${file.path}`,
    '@@ -1,1 +1,2 @@',
    `+${note}`,
    ` ${first}`,
  ].join('\n');
  return { path: file.path, kind: 'modify', diff };
}

function changeFor(task: PlanTask, index: number, locale: Locale): ProposedChange {
  const t = TEXT[locale];
  const path = `notes/${String(index + 1).padStart(2, '0')}-${slug(task.title, t.fallbackSlug)}.md`;
  const diff = [
    '--- /dev/null',
    `+++ b/${path}`,
    '@@ -0,0 +1,3 @@',
    `+# ${task.title}`,
    '+',
    `+${t.fileBody}`,
  ].join('\n');
  return { path, kind: 'create', diff };
}

/**
 * Deterministic, fully offline provider. It never touches the network or the
 * file system; it exists so the whole flow can be exercised without API keys.
 */
export function createMockProvider(options: MockProviderOptions = {}): AgentProvider {
  const latency = options.latencyMs ?? 0;
  const locale = options.locale ?? 'pt-BR';
  const t = TEXT[locale];

  async function step<T>(
    name: 'plan' | 'build' | 'review' | 'chat',
    signal: AbortSignal | undefined,
    produce: () => { output: T; input: string; text: string },
  ): Promise<ProviderResult<T>> {
    await delay(latency, t.aborted, signal);
    if (options.failOn === name) throw new Error(t.failure(name));
    const { output, input, text } = produce();
    return { output, usage: syntheticUsage(input, text) };
  }

  return {
    id: 'mock',
    label: 'Mock (offline)',
    offline: true,
    modelFor: () => 'mock',
    plan: (request, signal, tree) =>
      step<Plan>('plan', signal, () => {
        const files = tree?.length ? pickFiles(request, tree) : [];
        const plan: Plan = {
          summary: t.planSummary,
          tasks: splitIntoTasks(request, locale),
          ...(files.length ? { files } : {}),
        };
        return { output: plan, input: request, text: JSON.stringify(plan) };
      }),
    build: (plan, signal, files) =>
      step<ProposedChange[]>('build', signal, () => {
        const readable = files ?? [];
        const edits = readable
          .map((file, i) => modifyFor(file, plan.tasks[i % plan.tasks.length]!, locale))
          .filter((c): c is ProposedChange => c !== null);
        const changes = edits.length
          ? edits
          : plan.tasks.map((task, i) => changeFor(task, i, locale));
        return { output: changes, input: JSON.stringify(plan), text: JSON.stringify(changes) };
      }),
    review: (changes, signal) =>
      step<Review>('review', signal, () => {
        const review: Review =
          changes.length > 0
            ? { verdict: 'approve', comments: [t.reviewed(changes.length)] }
            : { verdict: 'request_changes', comments: [t.nothing] };
        return { output: review, input: JSON.stringify(changes), text: JSON.stringify(review) };
      }),
    chat: (agent, history, signal) =>
      step<string>('chat', signal, () => {
        const last = [...history].reverse().find((m) => m.from === 'user')?.content ?? '';
        const reply = mockReply(agent, last, locale);
        const input = history.map((m) => m.content).join('\n');
        return { output: reply, input, text: reply };
      }),
  };
}
